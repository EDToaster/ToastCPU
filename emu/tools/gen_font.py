#!/usr/bin/env python3
"""Regenerate emu/src/display/font.rs from the FPGA VGA driver.

The window renderer must draw exactly what the hardware draws, so the glyph
table is extracted from the `case` statement in fpga/src/drivers/vga_driver.sv
rather than maintained by hand.

Usage (from the repo root):
    python3 emu/tools/gen_font.py > emu/src/display/font.rs
"""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parents[2]
src = (root / "fpga/src/drivers/vga_driver.sv").read_text()

glyphs = {}
for code, bits in re.findall(r"8'h([0-9A-Fa-f]{2})\s*:\s*bitmap\s*=\s*48'h([0-9A-Fa-f]{12});", src):
    glyphs[int(code, 16)] = int(bits, 16)
assert len(glyphs) == 256, f"expected 256 glyphs, found {len(glyphs)}"

print("// @generated by emu/tools/gen_font.py from fpga/src/drivers/vga_driver.sv -- do not edit.")
print("//")
print("// Each glyph is 6x8 pixels packed MSB-first into the low 48 bits: pixel (x, y)")
print("// is bit `47 - (y * 6 + x)`, matching `logic [0:47] bitmap` in the driver.")
print()
print("pub const GLYPH_WIDTH: usize = 6;")
print("pub const GLYPH_HEIGHT: usize = 8;")
print()
print("pub const GLYPHS: [u64; 256] = [")
for i in range(0, 256, 4):
    row = ", ".join(f"0x{glyphs[c]:012X}" for c in range(i, i + 4))
    print(f"    {row}, // 0x{i:02X}")
print("];")
